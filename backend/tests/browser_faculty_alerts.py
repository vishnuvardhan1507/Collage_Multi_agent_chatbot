def model(prompt,payload):
    if prompt==GUARDRAIL_AGENT_PROMPT:
        return {'verdict':'allow','topic_scope':'college','modules':['attendance']}
    if payload['query']=='delete both':
        import time
        time.sleep(1)  # Allow the bell to open before the chat action completes.
        return {'route':'direct','alert_update':{'action':'delete','ids':[r['id'] for r in payload['alert_context']['owned_alerts']]}}
    return {'route':'direct','alert_update':{'action':'create','kind':'attendance_faculty',
        'config':{'threshold':73,'course_id':None,'student_id':None}}}


